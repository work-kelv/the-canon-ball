export interface Quote {
  text: string;
  cite: string;
  url?: string;
}

export interface Witness {
  id: string;
  name: string;
  /** Display dates, e.g. "c. 69 – 155". */
  life: string;
  from: number;
  to: number;
  era: EraId;
  stream: Stream;
  place: string;
  role: string;
  martyr?: boolean;
  about: string;
  /** How this person pointed to Jesus. */
  jesus: string;
  quote?: Quote;
  refs?: string;
}

export type EventKind = 'council' | 'persecution' | 'event';

export interface ChurchEvent {
  id: string;
  name: string;
  year: number;
  label: string;
  era: EraId;
  kind: EventKind;
  about: string;
  refs?: string;
}

